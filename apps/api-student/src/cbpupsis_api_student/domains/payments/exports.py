"""In-memory student payment receipt PDF."""

from __future__ import annotations

from datetime import UTC, datetime
from io import BytesIO
from zoneinfo import ZoneInfo

from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

MANILA = ZoneInfo("Asia/Manila")


def _format_paid_at(paid_at: datetime | None) -> str:
    """Format settlement timestamps in readable Asia/Manila (UTC+8) time."""
    if paid_at is None:
        return "Pending"
    aware = paid_at.replace(tzinfo=UTC) if paid_at.tzinfo is None else paid_at
    local = aware.astimezone(MANILA)
    hour = local.strftime("%I").lstrip("0") or "12"
    return f"{local:%B} {local.day}, {local:%Y} at {hour}:{local:%M %p} (UTC+8)"


def receipt_pdf(payment) -> bytes:
    """Render a deliberately card-data-free payment receipt."""
    buffer = BytesIO()
    page = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4
    page.setTitle(f"Payment receipt {payment.receipt_number}")
    page.setFont("Helvetica-Bold", 16)
    page.drawCentredString(
        width / 2, height - 72, "Polytechnic University of the Philippines"
    )
    page.setFont("Helvetica-Bold", 14)
    page.drawCentredString(width / 2, height - 100, "Official Payment Receipt")
    page.setFont("Helvetica", 10)
    lines = (
        ("Receipt number", payment.receipt_number),
        ("Payment ID", str(payment.id)),
        ("Amount", f"PHP {payment.amount:.2f}"),
        ("Status", payment.payment_status),
        ("Gateway reference", payment.gateway_reference or "Pending"),
        ("Paid at", _format_paid_at(payment.paid_at)),
    )
    y = height - 145
    for label, value in lines:
        page.setFont("Helvetica-Bold", 10)
        page.drawString(72, y, f"{label}:")
        page.setFont("Helvetica", 10)
        page.drawString(190, y, str(value))
        y -= 24
    page.setFont("Helvetica-Oblique", 8)
    page.drawString(
        72, 72, "Generated by CBPUPSIS. No card data is stored or displayed."
    )
    page.showPage()
    page.save()
    return buffer.getvalue()
